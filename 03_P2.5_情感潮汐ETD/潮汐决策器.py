# -*- coding: utf-8 -*-
"""
决策层：潮汐目标计算器
======================
第三套架构（情感潮汐解码 ETD）的决策模块。

根据情感轨迹 + 角色设定，算出"此刻该涌向哪里"的目标分布与引导强度：
1. 共情目标：V_target = V_用户当前 × β_共情 + 轨迹均值 × (1 - β_共情)
2. 角色基调叠加：若配置角色，目标向量朝角色 VAD 基线收敛
3. 引导强度自适应：α(t) = α_基 × (1 + Δarousal) × min(1, 轨迹活跃度)
4. 词汇预算：密度目标 = 密度_基 + 密度_增益 × |V_target|

灵感来源：语义回响的"情感先于表达"思想，但目标是外部连续情感状态
而非模型内部向量池。
"""
import math
import dataclasses
from typing import Optional, Tuple

from 潮汐感知器 import 潮汐感知器, 情感状态


@dataclasses.dataclass
class 角色基调:
    """角色 VAD 基线（可配置，默认共情型）"""
    名称: str
    valence: float  # 基础愉悦度
    arousal: float  # 基础唤醒度
    dominance: float  # 基础支配度


# 内置几个角色基调（便于评测脚本直接选用）
默认角色表 = {
    "共情": 角色基调("共情", 0.0, 0.3, 0.2),
    "温柔": 角色基调("温柔", 0.2, 0.1, 0.1),
    "活泼": 角色基调("活泼", 0.3, 0.5, 0.2),
    "沉稳": 角色基调("沉稳", 0.1, 0.1, 0.3),
    "悲伤": 角色基调("悲伤", -0.3, 0.2, 0.0),
}


class 潮汐决策器:
    """
    潮汐目标计算器

    用法
    ----
    >>> 感知器 = 潮汐感知器()
    >>> 决策器 = 潮汐决策器(感知器)
    >>> 目标 = 决策器.计算目标(用户当前状态)
    >>> print(目标.引导强度, 目标.密度目标)
    """

    def __init__(
        self,
        感知器: 潮汐感知器,
        β共情: float = 0.6,
        角色权重: float = 0.6,
        α基: float = 0.15,
        α上限: float = 0.5,
        密度基: float = 0.06,
        密度增益: float = 0.10,
        密度上限: float = 0.25,
        角色: Optional[角色基调] = None,
        活跃度窗口: int = 8,
    ) -> None:
        """
        Parameters
        ----------
        感知器 : 潮汐感知器
            共享的感知层实例（读取其情感轨迹）
        β共情 : float
            共情系数：无角色时控制目标"贴近用户"(→1) vs "保持自身稳定"(→0)
        角色权重 : float
            **角色主导权重（v2.1）**：有角色时目标 = 角色基调 × 角色权重
            + 共情基线 × (1-角色权重)。角色权重>0.5 即角色主导，
            引导方向稳定贴合角色（角色扮演/陪伴场景推荐 0.6~0.8）。
        α基 : float
            基础引导强度（决策层输出 α 的自适应基础）
        α上限 : float
            引导强度封顶，防止过度引导
        密度基 : float
            情感词密度目标的基础值（每句情感词数/句长）
        密度增益 : float
            密度目标随目标情感强度的增幅系数
        密度上限 : float
            密度目标封顶
        角色 : Optional[角色基调]
            角色 VAD 基线，None 时纯共情
        活跃度窗口 : int
            轨迹活跃度计算窗口（最近 N 轮）
        """
        if not (0.0 <= β共情 <= 1.0):
            raise ValueError(f"β共情 必须在 [0,1] 内，收到 {β共情}")
        if not (0.0 <= 角色权重 <= 1.0):
            raise ValueError(f"角色权重 必须在 [0,1] 内，收到 {角色权重}")
        if not (0.0 <= α基 <= 1.0):
            raise ValueError(f"α基 必须在 [0,1] 内，收到 {α基}")
        if not (0.0 <= α上限 <= 1.0):
            raise ValueError(f"α上限 必须在 [0,1] 内，收到 {α上限}")
        if 密度基 < 0 or 密度增益 < 0 or 密度上限 < 0:
            raise ValueError("密度参数不能为负")

        self.感知器 = 感知器
        self.β共情 = β共情
        self.角色权重 = 角色权重
        self.α基 = α基
        self.α上限 = α上限
        self.密度基 = 密度基
        self.密度增益 = 密度增益
        self.密度上限 = 密度上限
        self.角色 = 角色
        self.活跃度窗口 = 活跃度窗口

        # 决策日志（供裁判审计）
        self.决策日志: dict = {}

    def 计算目标(
        self,
        用户当前: Optional[情感状态] = None,
    ) -> "潮汐目标":
        """
        计算当前决策：目标情感状态 + 引导强度 + 词汇密度目标。

        Parameters
        ----------
        用户当前 : Optional[情感状态]
            用户最近一条消息的情感状态（由感知层测量得到）；
            为 None 时从轨迹推算。

        Returns
        -------
        潮汐目标
        """
        # ── 1. 共情目标 ──
        轨迹均值 = self._轨迹均值()
        if 用户当前 is None:
            # 只看用户的轨迹潮位
            用户当前 = self.感知器.当前潮位(忽略说话人="模型")

        v = 用户当前.valence * self.β共情 + 轨迹均值.valence * (1 - self.β共情)
        a = 用户当前.arousal * self.β共情 + 轨迹均值.arousal * (1 - self.β共情)
        d = 用户当前.dominance * self.β共情 + 轨迹均值.dominance * (1 - self.β共情)

        # ── 2. 角色基调叠加（v2.1：角色主导） ──
        if self.角色 is not None:
            # 角色权重>0.5 → 目标主要落在角色基调上，共情基线仅作微调
            v = v * (1 - self.角色权重) + self.角色.valence * self.角色权重
            a = a * (1 - self.角色权重) + self.角色.arousal * self.角色权重
            d = d * (1 - self.角色权重) + self.角色.dominance * self.角色权重

        目标状态 = 情感状态(self._限幅(v), self._限幅(a, 0.0, 1.0), self._限幅(d, 0.0, 1.0))

        # ── 3. 自适应引导强度 ──
        # Δarousal：用户当前唤醒度相对基线活跃度的增量（用户越激动越要引导）
        Δ唤醒 = max(0.0, 用户当前.arousal - 轨迹均值.arousal)
        活跃度 = self.感知器.轨迹活跃度(self.活跃度窗口)
        # 角色主导时：引导强度主要由目标情感强度决定（而非用户情绪波动）
        目标强度 = 目标状态.强度()
        活跃度有效 = max(活跃度, 目标强度)
        α = self.α基 * (1.0 + Δ唤醒 * 1.0) * min(1.0, 活跃度有效 * 2.5)
        α = min(self.α上限, α)

        # ── 4. 词汇密度目标 ──
        密度 = self.密度基 + self.密度增益 * 目标强度
        密度 = min(self.密度上限, 密度)

        # ── 记录决策日志 ──
        self.决策日志 = {
            "用户当前": self._状态转dict(用户当前),
            "轨迹均值": self._状态转dict(轨迹均值),
            "目标状态": self._状态转dict(目标状态),
            "α": round(α, 4),
            "密度目标": round(密度, 4),
            "活跃度": round(活跃度, 4),
            "角色": self.角色.名称 if self.角色 else None,
            "角色权重": self.角色权重,
        }

        return 潮汐目标(目标状态, α, 密度)

    # ──────────────────────────────────────────────
    # 内部工具
    # ──────────────────────────────────────────────

    def _轨迹均值(self) -> 情感状态:
        """全部轨迹点（含用户与模型）的均值，作为对话整体情感底色"""
        潮位 = self.感知器.当前潮位()
        return 潮位

    @staticmethod
    def _限幅(x: float, 低: float = -1.0, 高: float = 1.0) -> float:
        return max(低, min(高, x))

    @staticmethod
    def _状态转dict(状态: 情感状态) -> dict:
        return {
            "valence": round(状态.valence, 3),
            "arousal": round(状态.arousal, 3),
            "dominance": round(状态.dominance, 3),
        }

    def __repr__(self) -> str:
        return (f"潮汐决策器(β共情={self.β共情}, α基={self.α基}, "
                f"密度基={self.密度基}, 角色={self.角色.名称 if self.角色 else None})")


class 潮汐目标:
    """一次决策的输出：目标情感状态 + 引导强度 + 密度目标"""

    __slots__ = ("目标状态", "引导强度", "密度目标")

    def __init__(self, 目标状态: 情感状态, 引导强度: float, 密度目标: float) -> None:
        self.目标状态 = 目标状态
        self.引导强度 = 引导强度
        self.密度目标 = 密度目标

    def __repr__(self) -> str:
        return (f"潮汐目标({self.目标状态}, α={self.引导强度:.3f}, "
                f"密度={self.密度目标:.3f})")


