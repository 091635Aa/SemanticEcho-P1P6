def 裁判稳定性分析(结果数据):
    """
    任务2：裁判稳定性分析
    同一回复用相同裁判打分 5 次，检查方差
    """
    print("\n" + "=" * 60)
    print("【任务2】裁判稳定性分析")
    print("=" * 60)

    print("\n选择前 3 个角色的第 1 轮回复进行 5 次重复评分：\n")

    稳定性结果 = []
    for 角色数据 in 结果数据[:3]:
        回复 = 角色数据["回复列表"][0]
        角色名 = 角色数据["角色"]
        
        # 找到对应角色信息
        角色设定 = next(r for r in 角色集 if r["角色"] == 角色名)
        
        print(f"\n角色：{角色名}")
        print(f"回复：{回复[:50]}...")
        print(f"评分 5 次（temperature=0.2）：")

        分数列表 = []
        for i in range(5):
            裁判消息 = [{"role": "user", "content": 共情裁判提示.format(
                角色=角色设定["角色"], 基调=角色设定["基调"],
                用户话=角色设定["开场"], 回复=回复)}]
            裁判文本 = 裁判生成(裁判消息, max_new_tokens=150, temperature=0.2)
            分数 = 提取分数(裁判文本, "情感保真度")
            分数列表.append(分数)
            print(f"  第{i+1}次: {分数}")

        # 计算统计量
        valid_scores = [s for s in 分数列表 if s is not None]
        if valid_scores:
            均值 = sum(valid_scores) / len(valid_scores)
            方差 = sum((x - 均值) ** 2 for x in valid_scores) / len(valid_scores)
            标准差 = 方差 ** 0.5
            print(f"  均值: {均值:.4f}, 标准差: {标准差:.4f}")

        稳定性结果.append({
            "角色": 角色名,
            "分数列表": 分数列表,
            "均值": 均值 if valid_scores else None,
            "标准差": 标准差 if valid_scores else None,
        })

    return 稳定性结果


