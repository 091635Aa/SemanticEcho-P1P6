def 解析(文件):
    with open(os.path.join(目录, 文件), encoding="utf-8") as f:
        数据 = json.load(f)
    原始 = 数据.get("原始输出", "")
    m = re.search(r"\{.*\}", 原始, re.S)
    obj = None
    if m:
        try:
            obj = json.loads(m.group(0))
        except Exception:
            pass
    return 数据, obj

行 = []
for 文件, 说明 in 段配置:
    数据, obj = 解析(文件)
    if obj:
        行.append((说明, obj, 数据.get("推理耗时秒")))

