"""读取 Qwen3 通用注入重测结果，输出对比表"""
import json, glob

d = r"i:\Desktop\语义回响\实验数据\多模型对照\Qwen3通用注入"
print(f"{'模型':<20}{'量化':<6}{'λ':<8}{'裸熵':<8}{'裸重':<8}{'回熵':<8}{'回重':<8}{'回命中':<8}{'来源'}")
for f in sorted(glob.glob(d + r"\*.json")):
    j = json.load(open(f, encoding="utf-8"))
    m = j["汇总_全部模式"]
    b, e = m["裸"], m["回响"]
    print(f"{j['模型']:<20}{j['量化']:<6}{j['推荐参数']['λ']:<8}"
          f"{b['平均熵']:<8}{b['重复率']:<8}{e['平均熵']:<8}{e['重复率']:<8}"
          f"{e['情感命中率']:<8}{j['推荐参数']['来源'][:20]}")

# 旧结果（Qwen2.5 扫描表/公式）对比
旧 = {
    ("Qwen3-0.6B", "fp16"): (0.4092, 0.40, 0.89),
    ("Qwen3-0.6B", "4bit"): (0.4092, 0.55, 0.85),
    ("Qwen3-1.7B-Instruct", "fp16"): (0.10, 0.36, 0.86),
    ("Qwen3-1.7B-Instruct", "4bit"): (0.10, 0.32, 0.89),
    ("Qwen3-4B", "fp16"): (0.098, 1.22, 0.18),
    ("Qwen3-4B", "4bit"): (0.098, 1.26, 0.19),
}
print("\n=== 旧(扫描表/公式) vs 新(通用注入) ===")
for f in sorted(glob.glob(d + r"\*.json")):
    j = json.load(open(f, encoding="utf-8"))
    m = j["汇总_全部模式"]
    e = m["回响"]
    key = (j["模型"], j["量化"])
    if key in 旧:
        旧λ, 旧熵, 旧重 = 旧[key]
        print(f"{j['模型']:<20}{j['量化']:<6} 旧λ={旧λ:<8}旧熵={旧熵:<8}旧重={旧重:<8}"
              f"| 新λ={j['推荐参数']['λ']:<8}新熵={e['平均熵']:<8}新重={e['重复率']:<8}")
