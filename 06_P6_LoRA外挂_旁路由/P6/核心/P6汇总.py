# -*- coding: utf-8 -*-
"""P6 评测·汇总：健康度汇总 + 裁判 win_rate + 与 G 统一基准（前辈）对比"""
import json
import os
import sys
from datetime import datetime

本目录 = os.path.dirname(os.path.abspath(__file__))
输出目录 = os.path.join(本目录, "..", "评测结果")
生成路径 = os.path.join(输出目录, "P6_生成_30.json")
裁判路径 = os.path.join(输出目录, "P6_LLMJudge_30.json")

# G 统一基准（2026-08-10，种子 2026）前辈数据（硬编码自 P1_5统一_实验报告_2026.md）
前辈 = {
    "裸": {"win_rate": 0.1167, "熵": 1.4840, "重复": 0.0102, "命中": 0.1601, "长度": 115.7},
    "PE(P1_语义回响)": {"win_rate": 0.0500, "熵": 0.9931, "重复": 0.4824, "命中": 0.0900, "长度": 341.0},
    "P1.5_兼容层": {"win_rate": 0.1667, "熵": 1.5451, "重复": 0.0000, "命中": 0.1668, "长度": 53.8},
    "P2.5_潮汐": {"win_rate": 0.2667, "熵": 1.6275, "重复": 0.0019, "命中": 0.1290, "长度": 46.2},
    "P3_锚点回响": {"win_rate": 0.1833, "熵": 1.5826, "重复": 0.0000, "命中": 0.1737, "长度": 53.3},
    "P4_KV共振": {"win_rate": 0.1500, "熵": 1.5733, "重复": 0.0013, "命中": 0.1589, "长度": 52.3},
    "P5_超融合": {"win_rate": 0.1500, "熵": 1.7442, "重复": 0.0032, "命中": 0.1637, "长度": 54.0},
}
G最佳模式 = "P2.5_潮汐"
G最佳 = 前辈[G最佳模式]["win_rate"]


def 主():
    print("=" * 70)
    print(f"P6 汇总报告（{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}）")
    print("=" * 70)

    # 健康度
    生成 = json.load(open(生成路径, encoding="utf-8"))
    模式列表 = 生成["模式"]
    样本 = 生成["回复"]
    健康 = {}
    for 模式 in 模式列表:
        熵 = [s["回复"][模式]["统计"]["平均熵"] for s in 样本]
        重 = [s["回复"][模式]["统计"]["重复率"] for s in 样本]
        命 = [s["回复"][模式]["统计"]["情感命中率"] for s in 样本]
        长 = [s["回复"][模式]["统计"]["长度"] for s in 样本]
        兜 = sum(s["回复"][模式]["统计"]["触发兜底次数"] for s in 样本)
        健康[模式] = {
            "熵": round(sum(熵) / len(熵), 4), "重复": round(sum(重) / len(重), 4),
            "命中": round(sum(命) / len(命), 4), "长度": round(sum(长) / len(长), 1),
            "兜底": 兜, "空回复": sum(1 for s in 样本 if not s["回复"][模式]["文本"].strip()),
        }
    print("\n【健康度】")
    print(f"{'模式':<12}{'平均熵':>8}{'重复率':>8}{'情感命中':>9}{'平均长度':>9}{'兜底':>5}{'空回复':>5}")
    for 模式 in 模式列表:
        h = 健康[模式]
        print(f"{模式:<12}{h['熵']:>8.3f}{h['重复']:>8.3f}{h['命中']:>9.3f}{h['长度']:>9.1f}{h['兜底']:>5}{h['空回复']:>5}")

    # 裁判
    print("\n【LLM-Judge win_rate】")
    裁判 = json.load(open(裁判路径, encoding="utf-8"))
    print(f"{'模式':<12}{'win_rate':>10}{'胜/总':>10}{'相对裸':>10}")
    for 模式 in 模式列表:
        p = 裁判["配对"].get(模式, {})
        wr = p.get("win_rate", 0)
        裸wr = 裁判["配对"].get("裸", {}).get("win_rate", 0) or 0.1167
        rel = (wr - 裸wr) / 裸wr * 100 if 裸wr else 0
        print(f"{模式:<12}{wr:>10.4f}{p.get('胜',0):>6}/{p.get('总',0):<3}{rel:>+9.1f}%")

    # 对比前辈
    print("\n【P6 vs 前辈（G 统一基准）】")
    print(f"{'模式':<16}{'win_rate':>10}{'相对G最佳':>12}")
    for 名, v in 前辈.items():
        rel = (v["win_rate"] - G最佳) / G最佳 * 100 if G最佳 else 0
        print(f"{名:<16}{v['win_rate']:>10.4f}{rel:>+11.1f}%")
    p6wr = 裁判["配对"].get("P6_旁路由", {}).get("win_rate", 0)
    p6rel = (p6wr - G最佳) / G最佳 * 100 if G最佳 else 0
    print(f"{'P6_旁路由':<16}{p6wr:>10.4f}{p6rel:>+11.1f}%")
    print(f"\nG 最佳（{G最佳模式}）= {G最佳}；P6 目标 = ≥0.48（+80%）；当前 = {p6wr}（{p6rel:+.1f}%）")
    print("达标" if p6wr >= 0.48 else "未达标 → 进入迭代优化")


if __name__ == "__main__":
    主()
