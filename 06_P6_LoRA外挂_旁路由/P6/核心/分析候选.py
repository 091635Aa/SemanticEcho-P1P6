def 串情感命中(文本):
    return sum(1 for w in 情感词 if w in 文本)

def 评分2(文本):
    L = len(文本)
    长度分 = 1.0 - abs(L - 40)/80.0 if 10 <= L <= 80 else (-0.5 if L < 10 else -1.0)
    ai = sum(1 for w in AI腔 if w in 文本)
    shuo = sum(1 for w in 说教词 if w in 文本)
    kou = sum(1 for w in 口语词 if w in 文本)
    emo = 串情感命中(文本)
    # 改良：口语奖励、说教惩罚、AI腔惩罚、情感、长度
    return 2.5*emo + 1.2*max(长度分,0) - ai - 1.2*shuo + 0.6*min(kou,4)

改进数 = 0
候选过少 = 0
总候选 = 0
for s in 回复:
    候选 = s['回复']['P6_旁路由'].get('候选', [])
    if not 候选:
        候选过少 += 1
        continue
    总候选 += len(候选)
    旧选 = s['回复']['P6_旁路由']['文本']
    新选 = max(候选, key=lambda c: 评分2(c['文本']))
    if 新选['文本'] != 旧选:
        改进数 += 1

print(f"候选统计: 30 样本共 {总候选} 候选（平均 {总候选/30:.1f}/样本），候选缺失样本 {候选过少}")
print(f"改良评分后: {改进数}/30 样本换了选择")
print()

