# 扩展：模板生成额外样本
扩展模板 = [
    ("{q}", "{r}"),
    ("{q}，我好难过。", "{r}，难过的时候记得给自己一个拥抱。"),
    ("问问你，{q}", "谢谢你把心事告诉我，{r}"),
    ("{q}？", "{r}，没关系的。"),
]
扩展样本 = []
for q, r in 样本:
    for 模板q, 模板r in 扩展模板:
        if len(扩展样本) >= 60:
            break
        扩展样本.append((模板q.format(q=q), 模板r.format(r=r)))

全部 = 样本 + 扩展样本
# 打乱
random.shuffle(全部)
全部 = 全部[:150]

with open(输出路径, "w", encoding="utf-8") as f:
    for q, r in 全部:
        f.write(json.dumps({"instruction": q, "response": r}, ensure_ascii=False) + "\n")

print(f"数据集生成完成: {len(全部)} 条 → {输出路径}")
