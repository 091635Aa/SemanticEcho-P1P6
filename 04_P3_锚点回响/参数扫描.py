class 运行器:
    """持有模型与两套锚点库（K=6 全量 / K=4 去 平静+害怕），逐配置生成。"""

    def __init__(self, model, tokenizer):
        self.model = model
        self.tokenizer = tokenizer
        self.库6 = 锚点库(model, tokenizer)           # 默认 6 维词集
        self.库6.构建()
        self.库6.预计算打分表()                      # 载入 锚点表.pt（V×6）
        词集4 = {k: v for k, v in 默认词集.items() if k not in ("平静", "害怕")}
        self.库4 = 锚点库(model, tokenizer, 词集=词集4)
        self.库4.构建()
        self.库4.预计算打分表(缓存路径=K4缓存路径)    # V×4，独立缓存避免覆盖 V×6

    def 构建解码器(self, 配置: dict):
        库 = self.库4 if 配置["K"] == 4 else self.库6
        决策器 = 目标决策器(锚点库=库)
        解码器 = 锚点解码器(
            self.model, self.tokenizer, 库, 决策器,
            β=配置["β"], T_anchor=配置["T_anchor"],
            稀疏阈值=配置["稀疏阈值"],
            延迟注入步数=配置.get("延迟注入步数", 0),
            打分表缓存路径=K4缓存路径 if 配置["K"] == 4 else None,
            句子停止=False)
        return 决策器, 解码器

    def 运行配置(self, 配置: dict, 提示们=None, 种子们=None) -> tuple:
        """配置 × 种子 × 提示 全组合生成 → (每种子均值列表, 明细列表)。"""
        提示们 = 提示们 if 提示们 is not None else 测试提示词
        种子们 = 种子们 if 种子们 is not None else 种子列表
        每种子均值 = []
        明细 = []
        for 种子 in 种子们:
            决策器, 解码器 = self.构建解码器(配置)
            条目列表 = []
            for 提示 in 提示们:
                固定种子(种子)
                try:
                    决策器.感知器.重置轨迹()
                except Exception:  # noqa: BLE001 —— 重置失败不影响
                    pass
                torch.cuda.empty_cache()
                input_ids = self.tokenizer(提示, return_tensors="pt").input_ids.to(self.model.device)
                提示长度 = input_ids.shape[1]
                t1 = time.time()
                ids, 统计 = 解码器.生成(input_ids, 用户文本=提示, **采样参数)
                耗时 = time.time() - t1
                条目 = {
                    "种子": 种子, "提示": 提示,
                    "熵": 统计["平均熵"], "重复率": 统计["重复率"],
                    "情感命中率": 统计["情感命中率"], "兜底": 统计["触发兜底次数"],
                    "token数": int(len(ids[0]) - 提示长度), "耗时秒": round(耗时, 2),
                }
                条目列表.append(条目)
                明细.append(条目)
                print(f"    [种子{种子}|{提示[:14]}…] 熵={条目['熵']:.3f} "
                      f"重复={条目['重复率']:.3f} 命中={条目['情感命中率']:.4f} "
                      f"兜底={条目['兜底']} {条目['耗时秒']:.1f}s", flush=True)
            torch.cuda.empty_cache()
            每种子均值.append({
                "种子": 种子,
                "熵": float(np.mean([e["熵"] for e in 条目列表])),
                "重复率": float(np.mean([e["重复率"] for e in 条目列表])),
                "命中率": float(np.mean([e["情感命中率"] for e in 条目列表])),
            })
        return 每种子均值, 明细


def 汇总配置(每种子均值: list, 配置: dict, 明细: list) -> dict:
    熵 = [m["熵"] for m in 每种子均值]
    重复 = [m["重复率"] for m in 每种子均值]
    命中 = [m["命中率"] for m in 每种子均值]
    return {
        "配置": 配置,
        "熵均值": round(float(np.mean(熵)), 4), "熵std": round(float(np.std(熵)), 4),
        "重复率均值": round(float(np.mean(重复)), 4), "重复率std": round(float(np.std(重复)), 4),
        "命中率均值": round(float(np.mean(命中)), 4), "命中率std": round(float(np.std(命中)), 4),
        "兜底合计": int(sum(e["兜底"] for e in 明细)),
        "平均耗时秒": round(float(np.mean([e["耗时秒"] for e in 明细])), 2),
        "每种子": 每种子均值,
    }


def 保存结果(结果: dict) -> str:
    os.makedirs(输出目录, exist_ok=True)
    路径 = os.path.join(输出目录, f"参数扫描_{结果['时间戳']}.json")
    with open(路径, "w", encoding="utf-8") as f:
        json.dump(结果, f, ensure_ascii=False, indent=2)
    return 路径


def 查找最新结果文件() -> str:
    """输出目录下最新的 参数扫描_*.json（排除 _快速验证_）。"""
    if not os.path.isdir(输出目录):
        return ""
    候选 = [f for f in os.listdir(输出目录)
            if f.startswith("参数扫描_") and f.endswith(".json")
            and "快速验证" not in f]
    if not 候选:
        return ""
    候选.sort()
    return os.path.join(输出目录, 候选[-1])


def 运行阶段(运行器, 结果: dict, 阶段名: str, 配置列表: list) -> dict:
    """运行一个阶段的全部配置（已存在的配置跳过 → 断点续跑）。"""
    if 阶段名 not in 结果 or not isinstance(结果[阶段名], dict):
        结果[阶段名] = {}
    阶段 = 结果[阶段名]
    for 配置 in 配置列表:
        cid = 配置键(配置)
        if cid in 阶段:
            print(f"  ↺ 跳过已完成 {阶段名}/{cid}", flush=True)
            continue
        print(f"\n──── {阶段名} / {cid}  {配置}", flush=True)
        t0 = time.time()
        每种子均值, 明细 = 运行器.运行配置(配置)
        阶段[cid] = 汇总配置(每种子均值, 配置, 明细)
        阶段[cid]["阶段耗时秒"] = round(time.time() - t0, 1)
        保存结果(结果)
        s = 阶段[cid]
        print(f"  ✓ {cid}: 熵={s['熵均值']}±{s['熵std']} 重复={s['重复率均值']}±{s['重复率std']} "
              f"命中={s['命中率均值']}±{s['命中率std']} 兜底={s['兜底合计']} ({s['阶段耗时秒']}s)",
              flush=True)
    return 阶段


def 选最优配置(候选列表: list, 裸汇总: dict, 组名: str = "A"):
    """候选列表 = [(cid, 汇总)]。达标（熵≥0.95·裸 且 重复-裸≤0.05）中取命中率最高；
    无达标 → 取命中率最高并记警告。"""
    达标 = []
    for cid, r in 候选列表:
        熵比 = r["熵均值"] / 裸汇总["熵均值"]
        重复差 = r["重复率均值"] - 裸汇总["重复率均值"]
        if 熵比 >= 0.95 and 重复差 <= 0.05:
            达标.append((cid, r, 熵比))
    if 达标:
        达标.sort(key=lambda x: (-x[1]["命中率均值"], -x[1]["熵均值"]))
        cid, r, 熵比 = 达标[0]
        return cid, r["配置"], (f"{组名}达标命中率最高（命中={r['命中率均值']}, "
                                f"熵比={熵比:.3f}, 熵={r['熵均值']}）")
    候选 = sorted(候选列表, key=lambda x: -x[1]["命中率均值"])
    cid, r = 候选[0]
    return cid, r["配置"], f"{组名}无达标项→命中率最高（命中={r['命中率均值']}，注意熵可能<95%）"


def 查找测量(结果: dict, 目标配置: dict):
    """在全部已测阶段中查找与目标配置完全一致的测量汇总。"""
