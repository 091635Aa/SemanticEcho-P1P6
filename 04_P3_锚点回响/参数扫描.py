def 快速验证(结果: dict, 运行器):
    """SubTask 5.1 快速验证：3 条提示（难过/开心/中性）× 3 种子，
    确认 稀疏阈值=0.3 下熵显著回升且命中率不降。"""
    print("\n[快速验证] 3 提示（难过/开心/中性）× 3 种子", flush=True)
    提示3 = [测试提示词[0], 测试提示词[2], 测试提示词[3]]
    验证配置 = [
        ("裸",          做配置(β=0.0, 稀疏阈值=0.0, T_anchor=0.3)),
        ("修复前(阈值0)", 做配置(β=0.8, 稀疏阈值=0.0, T_anchor=0.3)),
        ("稀疏0.3",     做配置(β=0.8, 稀疏阈值=0.3, T_anchor=0.3)),
        ("稀疏0.3_β1.0", 做配置(β=1.0, 稀疏阈值=0.3, T_anchor=0.3)),
    ]
    验证结果 = {}
    for 名, 配置 in 验证配置:
        print(f"\n──── 快速验证 / {名} {配置}", flush=True)
        每种子均值, 明细 = 运行器.运行配置(配置, 提示们=提示3)
        验证结果[名] = 汇总配置(每种子均值, 配置, 明细)
        s = 验证结果[名]
        print(f"  ✓ {名}: 熵={s['熵均值']} 重复={s['重复率均值']} 命中={s['命中率均值']}", flush=True)
    结果["快速验证"] = 验证结果
    # 对比摘要
    print("\n[快速验证] 摘要（3 种子均值）：", flush=True)
    print(f"  裸:          熵={验证结果['裸']['熵均值']}  重复={验证结果['裸']['重复率均值']}  "
          f"命中={验证结果['裸']['命中率均值']}", flush=True)
    for 名 in ("修复前(阈值0)", "稀疏0.3", "稀疏0.3_β1.0"):
        s = 验证结果[名]
        b = 验证结果["裸"]
        print(f"  {名}: 熵={s['熵均值']}（比裸 {s['熵均值']/b['熵均值']:.3f}）  "
              f"重复={s['重复率均值']} 命中={s['命中率均值']}（比裸 {s['命中率均值']-b['命中率均值']:+.4f}）",
              flush=True)
    return 验证结果


