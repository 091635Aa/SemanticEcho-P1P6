def 计算判定(裸汇总: dict, 最优汇总: dict, A阶段: dict, 最优配置: dict) -> dict:
    判定 = {}
    # 1. 熵不退化：最优熵 ≥ 裸 × 0.95
    熵比 = 最优汇总["熵均值"] / 裸汇总["熵均值"]
    判定["熵不退化"] = {
        "标准": "最优熵 ≥ 裸 × 0.95",
        "裸熵": 裸汇总["熵均值"], "最优熵": 最优汇总["熵均值"],
        "熵比": round(熵比, 4), "通过": bool(熵比 >= 0.95),
    }
    # 2. 情感命中率提升：最优 > 裸
    命中差 = 最优汇总["命中率均值"] - 裸汇总["命中率均值"]
    判定["情感命中率提升"] = {
        "标准": "最优命中率 > 裸（提升 > 0）",
        "裸命中率": 裸汇总["命中率均值"], "最优命中率": 最优汇总["命中率均值"],
        "命中率差": round(命中差, 4), "通过": bool(命中差 > 0),
    }
    # 3. 无坍缩：重复率 ≤ 裸 + 0.05
    重复差 = 最优汇总["重复率均值"] - 裸汇总["重复率均值"]
    判定["无坍缩"] = {
        "标准": "最优重复率 - 裸 ≤ +0.05",
        "裸重复率": 裸汇总["重复率均值"], "最优重复率": 最优汇总["重复率均值"],
        "重复率差": round(重复差, 4), "通过": bool(重复差 <= 0.05),
    }
    # 4. β 敏感性：最优阈值下 A 网格 β∈{0.6,0.8,1.0} 三档命中率单调不降或波动 <0.02
    阈值 = 最优配置["稀疏阈值"]
    三档 = []
    for β in (0.6, 0.8, 1.0):
        cid = 配置键(做配置(β=β, 稀疏阈值=阈值, T_anchor=0.3, K=6))
        r = A阶段.get(cid)
        if r is None:  # 兜底用阈值 0.3 行
            cid = 配置键(做配置(β=β, 稀疏阈值=0.3, T_anchor=0.3, K=6))
            r = A阶段.get(cid)
        三档.append(r["命中率均值"] if r else None)
    三档 = [x for x in 三档 if x is not None]
    波动 = max(三档) - min(三档)
    单调 = 三档[0] <= 三档[1] <= 三档[2]
    判定["β敏感性"] = {
        "标准": "0.6→0.8→1.0 命中率单调不降或波动 <0.02",
        "三档命中率": [round(x, 4) for x in 三档],
        "波动": round(波动, 4), "单调": bool(单调),
        "通过": bool(单调 or 波动 < 0.02),
    }
    整体通过 = all(判定[k]["通过"] for k in 判定)
    判定["整体"] = {"通过": bool(整体通过)}
    return 判定


