    print(f"  最优A: {cidA} — {说明A}", flush=True)

    # ══════════════════════════════════════════════
    # 阶段 B：T_anchor 扫描（最优A 的 阈值/β）
    # ══════════════════════════════════════════════
    print("\n[阶段B] T_anchor 扫描", flush=True)
    B列表 = [做配置(β=配置A["β"], 稀疏阈值=配置A["稀疏阈值"], T_anchor=T, K=6)
             for T in (0.15, 0.3, 0.5)]
    运行阶段(运行, 结果, "阶段B_T扫描", B列表)
    B阶段 = 结果["阶段B_T扫描"]
    # 最优总：A 全部 + B 新增（键去重，B 与 A 同键以 A 为准，绝不含弃已测候选）
    A键 = {cid for cid, _ in 候选A}
    B新增 = [(cid, r) for cid, r in B阶段.items() if cid not in A键]
    候选AB = 候选A + B新增
    cid总, 配置总, 说明总 = 选最优配置(候选AB, 裸, "A+B")
    结果["最优总"] = {"cid": cid总, "配置": 配置总, "说明": 说明总}
    保存结果(结果)
    print(f"  最优总: {cid总} — {说明总}", flush=True)

    # ══════════════════════════════════════════════
    # 阶段 C：K 对比（最优配置下 K=6 vs K=4）
    # ══════════════════════════════════════════════
    print("\n[阶段C] 锚点维度 K 对比", flush=True)
    C列表 = [做配置(β=配置总["β"], 稀疏阈值=配置总["稀疏阈值"],
                  T_anchor=配置总["T_anchor"], K=4)]
    运行阶段(运行, 结果, "阶段C_K对比", C列表)
    # K=6 数据直接引用 最优总 的测量（同配置，避免重复 150s）
    k6测量 = 查找测量(结果, 配置总)
    if k6测量 is not None:
        结果["阶段C_K对比"].setdefault("（K=6 引用最优总）", k6测量)
    print(f"  K=6 复用最优总测量：熵={k6测量['熵均值']} 命中={k6测量['命中率均值']}", flush=True)

    # ══════════════════════════════════════════════
    # 阶段 D：过注入边界（最优配置 β → 1.6 / 2.0）
    # ══════════════════════════════════════════════
    print("\n[阶段D] 过注入边界（β=1.6 / 2.0）", flush=True)
    D列表 = [做配置(β=β, 稀疏阈值=配置总["稀疏阈值"],
                  T_anchor=配置总["T_anchor"], K=配置总["K"])
             for β in (1.6, 2.0)]
    运行阶段(运行, 结果, "阶段D_过注入", D列表)

    # ══════════════════════════════════════════════
    # 阶段 E（SubTask 5.3）：复核 裸 vs 最优
    # ══════════════════════════════════════════════
    print("\n[阶段E] 复核对照（裸 vs 最优）", flush=True)
    最优汇总 = 查找测量(结果, 配置总)
    if 最优汇总 is None:
        print("⚠ 最优配置无现成测量，重跑 …", flush=True)
        每种子均值, 明细 = 运行.运行配置(配置总)
        最优汇总 = 汇总配置(每种子均值, 配置总, 明细)
        结果["阶段D_过注入"][配置键(配置总)] = 最优汇总  # 暂存
    判定 = 计算判定(裸, 最优汇总, A阶段, 配置总)
    结果["复核"] = {"裸": 裸, "最优汇总": 最优汇总, "最优配置": 配置总, "判定": 判定}
    保存结果(结果)
    for k, v in 判定.items():
        if k == "整体":
            continue
        print(f"  {k}: {'✓ 通过' if v['通过'] else '✗ 不通过'} {v}", flush=True)
    print(f"  整体: {'通过 ✓' if 判定['整体']['通过'] else '不通过 ✗'}", flush=True)

    结果["总耗时秒"] = round(time.time() - t0, 1)
    路径 = 保存结果(结果)
    print(f"\n结果已保存: {路径}", flush=True)

    报告路径 = 生成报告(结果)
    print(f"报告已生成: {报告路径}", flush=True)
    print(f"总耗时 {结果['总耗时秒']}s | 整体判定: {'通过 ✓' if 判定['整体']['通过'] else '不通过 ✗'}",
          flush=True)
    return 0 if 判定["整体"]["通过"] else 1


